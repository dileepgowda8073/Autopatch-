import React from 'react'
import { Finding, SOURCE_LABELS } from '@/types'
import { TiltCard } from '../common/TiltCard'
import { SeverityBadge } from '../common/SeverityBadge'

export interface FindingCardProps {
  finding: Finding
  onClick?: () => void
  isSelected?: boolean
}

export const FindingCard: React.FC<FindingCardProps> = ({
  finding,
  onClick,
  isSelected = false,
}) => {
  const toolBadgeStyles: Record<string, string> = {
    ruff: 'bg-emerald-500/10 text-emerald-400 border-emerald-500/30',
    bandit: 'bg-red-500/10 text-red-400 border-red-500/30',
    pytest: 'bg-violet-500/10 text-violet-400 border-violet-500/30',
    llm: 'bg-cyan-500/10 text-cyan border-cyan-500/30',
    javac: 'bg-orange-500/10 text-orange-400 border-orange-500/30',
    spotbugs: 'bg-amber-500/10 text-amber-400 border-amber-500/30',
    checkstyle: 'bg-blue-500/10 text-blue-400 border-blue-500/30',
    junit: 'bg-purple-500/10 text-purple-400 border-purple-500/30',
  }

  return (
    <TiltCard
      intensity={3}
      onClick={onClick}
      className={`
        p-5 transition-all cursor-pointer
        ${
          isSelected
            ? 'border-cyan/60 shadow-[0_0_25px_rgba(0,245,255,0.2)] bg-cyan/[0.04]'
            : 'hover:border-white/[0.18]'
        }
      `}
    >
      {/* Header chips: Severity, Source, Candidate flag */}
      <div className="flex flex-wrap items-center gap-2 mb-3">
        <SeverityBadge severity={finding.severity} />

        <span
          className={`
            px-2 py-0.5 rounded-full border text-[11px] font-mono uppercase tracking-wider
            ${toolBadgeStyles[finding.source] || 'bg-white/[0.05] text-text-secondary border-white/10'}
          `}
        >
          {SOURCE_LABELS[finding.source] || finding.source}
        </span>

        {finding.is_candidate && (
          <span
            title="Candidate finding generated by AI analysis; requires developer confirmation."
            className="px-2 py-0.5 rounded-full border text-[11px] font-mono text-amber-400 bg-amber-500/10 border-amber-500/30 flex items-center gap-1"
          >
            <span>⚠</span>
            <span>Candidate</span>
          </span>
        )}

        <span className="ml-auto text-xs font-mono text-text-muted truncate">
          {finding.file}:{finding.line_start}
        </span>
      </div>

      {/* Finding Title */}
      <h3 className="text-base font-semibold text-white mb-2 leading-snug">
        {finding.title}
      </h3>

      {/* Description clamp */}
      <p className="text-sm text-text-secondary line-clamp-2 mb-3 leading-relaxed">
        {finding.description}
      </p>

      {/* Root-cause snippet */}
      <div className="p-2.5 rounded bg-black/40 border border-white/[0.04] mb-3">
        <p className="text-xs font-mono text-text-muted line-clamp-1 italic">
          <span className="text-cyan/80 not-italic font-semibold">Cause: </span>
          {finding.root_cause}
        </p>
      </div>

      {/* Footer metadata: Confidence estimate note */}
      <div className="flex items-center justify-between text-xs font-mono text-text-muted pt-2 border-t border-white/[0.04]">
        <span>
          Confidence (Est.):{' '}
          <strong className="text-text-primary">
            {Math.round(finding.confidence_estimate * 100)}%
          </strong>
        </span>
        <span className="text-[11px] text-text-muted italic">
          AI estimate — not a measured probability
        </span>
      </div>
    </TiltCard>
  )
}
